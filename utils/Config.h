#pragma once
#include <string>

/**
 * @file Config.h
 * @brief Параметры запуска приложения
 */

/// \brief Параметры приложения — простая структура данных без скрытого состояния.
///
/// Создаётся один раз в main() и передаётся в FileMonitor через конструктор.
/// Загрузка из файла выполняется фабричным методом fromFile().
struct Config {
    int         pollInterval = 1;      ///< Интервал опроса файлов в секундах
    std::string logLevel     = "INFO"; ///< Уровень логирования (INFO / WARN / ERROR)

    /// \brief Создаёт Config из файла формата key=value.
    ///
    /// Строки с '#' — комментарии, пропускаются.
    /// Нераспознанные ключи игнорируются.
    /// \param path Путь к конфигурационному файлу.
    /// \return Config с загруженными полями (или значениями по умолчанию при ошибке).
    static Config fromFile(const std::string& path);
};
