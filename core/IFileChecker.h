#pragma once
#include <string>

/**
 * @file IFileChecker.h
 * @brief Интерфейс стратегии проверки изменений файла
 */

/// \brief Описание единичного события изменения файла.
struct FileEvent {
    std::string path;        ///< Абсолютный или относительный путь к файлу
    std::string description; ///< Человекочитаемое описание произошедшего
};

/// \brief Интерфейс стратегии проверки файла (ISP, OCP).
///
/// Каждая реализация отвечает за отслеживание одного конкретного свойства файла
/// (существование, размер, восстановление после удаления).
/// Новые виды проверок добавляются без изменения FileMonitor (OCP).
class IFileChecker {
public:
    virtual ~IFileChecker() = default;

    /// \brief Проверяет, изменилось ли отслеживаемое свойство файла.
    ///
    /// Side-effect: обновляет внутреннее состояние для следующего сравнения.
    /// Первый вызов считается базовым снимком — всегда возвращает false.
    /// \param path Путь к файлу.
    /// \return true если свойство изменилось с момента последнего вызова.
    virtual bool hasChanged(const std::string& path) = 0;

    /// \brief Возвращает описание последнего обнаруженного события.
    ///
    /// Вызывается только после того, как hasChanged() вернул true.
    /// \param path Путь к файлу.
    /// \return Объект события с путём и описанием.
    virtual FileEvent getEvent(const std::string& path) const = 0;
};
